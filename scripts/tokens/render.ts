// Renders resolved tokens into CSS (variables, @theme, @utility), a typed TS module and a flat JSON file.
import {
  checkContrast,
  flatten,
  loadContrastPairs,
  loadTree,
  resolveTokens,
  type Token,
} from "./lib"

const HEADER = "AUTO-GENERATED by scripts/build-tokens.ts from tokens/*.json. Do not edit by hand; run `bun run tokens`."

type Typography = {
  fontSize: string
  lineHeight: string
  fontWeight: number
  letterSpacing?: string
  fontFamily?: string
}

const SPACING_ALIASES: Record<string, string> = {
  control: "control-h",
  "control-sm": "control-h-sm",
  "control-lg": "control-h-lg",
  row: "row-h",
  "row-head": "row-head-h",
  icon: "icon-size",
  gutter: "page-gutter",
  hit: "hit-min",
}

function group(resolved: Map<string, Token>, prefix: string) {
  return [...resolved.values()].filter((t) => t.path[0] === prefix)
}

function cssVarValue(token: Token) {
  if (token.ref?.startsWith("palette.")) return `var(--${token.ref.replaceAll(".", "-")})`
  return String(token.value)
}

function fontStack(value: unknown) {
  return (value as string[]).map((f) => (f.includes(" ") ? `"${f}"` : f)).join(", ")
}

export function render() {
  const resolved = resolveTokens(flatten(loadTree()))
  const palette = group(resolved, "palette")
  const colors = group(resolved, "color")
  const radius = group(resolved, "radius")
  const shadows = group(resolved, "shadow")
  const fonts = group(resolved, "font")
  const motion = group(resolved, "motion")
  const types = group(resolved, "type")
  const density = group(resolved, "density")
  const contrast = checkContrast(resolved, loadContrastPairs())

  const lines: string[] = [`/* ${HEADER} */`, "", ":root {", "  /* Primitive palette (do not use directly) */"]
  for (const t of palette) lines.push(`  --${t.path.join("-")}: ${t.value};`)
  lines.push("", "  /* Semantic colors */")
  for (const t of colors) lines.push(`  --${t.path.slice(1).join("-")}: ${cssVarValue(t)};`)
  lines.push("", "  /* Fonts */")
  for (const t of fonts) lines.push(`  --font-family-${t.path[1]}: ${fontStack(t.value)};`)
  lines.push("", "  /* Radius base (used by calc() inside some shadcn components) */")
  lines.push(`  --radius: ${resolved.get("radius.lg")?.value};`)
  lines.push("", "  /* Motion */")
  for (const t of motion) lines.push(`  --duration-${t.path[1]}: ${t.value};`)
  lines.push("}", "")

  const densityModes = [...new Set(density.map((t) => t.path[1]))]
  for (const mode of densityModes) {
    const selector = mode === "comfortable" ? `:root,\n[data-density="comfortable"]` : `[data-density="${mode}"]`
    lines.push(`${selector} {`)
    for (const t of density.filter((d) => d.path[1] === mode)) lines.push(`  --${t.path[2]}: ${t.value};`)
    lines.push("}", "")
  }

  lines.push("@theme inline {")
  for (const t of colors) {
    const name = t.path.slice(1).join("-")
    lines.push(`  --color-${name}: var(--${name});`)
  }
  lines.push("")
  for (const t of fonts) lines.push(`  --font-${t.path[1]}: var(--font-family-${t.path[1]});`)
  lines.push("  --font-heading: var(--font-sans);", "")
  for (const t of radius) {
    const name = t.path[1] === "full" ? "4xl" : t.path[1]
    lines.push(`  --radius-${name}: ${t.value};`)
  }
  lines.push(`  --radius-3xl: ${resolved.get("radius.2xl")?.value};`, "")
  for (const [alias, variable] of Object.entries(SPACING_ALIASES)) lines.push(`  --spacing-${alias}: var(--${variable});`)
  lines.push("}", "", "@theme {")
  for (const t of shadows) lines.push(`  --shadow-${t.path[1]}: ${t.value};`)
  lines.push("}", "")

  for (const t of types) {
    const v = t.value as Typography
    if (t.description) lines.push(`/* ${t.description} */`)
    lines.push(`@utility type-${t.path[1]} {`)
    if (v.fontFamily) lines.push(`  font-family: ${v.fontFamily};`)
    lines.push(`  font-size: ${v.fontSize};`, `  line-height: ${v.lineHeight};`, `  font-weight: ${v.fontWeight};`)
    if (v.letterSpacing) lines.push(`  letter-spacing: ${v.letterSpacing};`)
    lines.push("}", "")
  }
  const css = lines.filter((line, i, all) => !(line === "" && all[i - 1] === "")).join("\n").trimEnd() + "\n"

  const pick = (tokens: Token[], depth = 1) =>
    tokens.map((t) => ({
      name: t.path.slice(depth).join("."),
      value: t.value,
      ref: t.ref ?? "",
      description: t.description ?? "",
    }))

  const data = {
    palette: pick(palette),
    colors: pick(colors),
    radius: pick(radius),
    shadows: pick(shadows),
    fonts: pick(fonts),
    motion: pick(motion),
    type: pick(types),
    spacing: pick(group(resolved, "spacing")),
    breakpoints: pick(group(resolved, "breakpoint")),
    density: pick(density),
    contrast,
  }

  const ts = `// ${HEADER}\n\nexport const tokens = ${JSON.stringify(data, null, 2)} as const\n\nexport type Tokens = typeof tokens\n`
  const json = JSON.stringify(Object.fromEntries([...resolved].map(([k, t]) => [k, t.value])), null, 2) + "\n"

  return { css, ts, json, contrast }
}
